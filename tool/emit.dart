// The emitter of monorithm_ui. It reads only the intermediate form (IR) of the language: ir/<version>/ of the
// submodule language/ (monorithm/design at a tag), at the version of that checkout. It writes:
//   lib/src/tokens/tokens.g.dart   the tokens as Dart constants
//
//   dart run tool/emit.dart           write the file
//   dart run tool/emit.dart --check   fail if a file of the IR does not match its checksum in the manifest, or if the
//                                     committed file differs from the output (the drift check of CI)
//
// This emitter is a stub. It writes the axes and the tokens of four types: color, dimension, duration, and number.
// The other types (cubicBezier, fontWeight, shadow, transition) come with the components that use them.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

/// The folder of the submodule of the language.
const languageDir = 'language';

/// The generated file.
const output = 'lib/src/tokens/tokens.g.dart';

/// The language version: the version of the checked-out language source.
String languageVersion() =>
    (_json('$languageDir/package.json') as Map<String, dynamic>)['version']
        as String;

/// The IR of that version.
String irDir() => '$languageDir/ir/${languageVersion()}';

Object? _json(String path) => jsonDecode(File(path).readAsStringSync());

/// Stops with an error if a file of the IR does not match its checksum in the manifest, or if the versions differ.
void verifyIr() {
  final dir = irDir();
  final manifest = _json('$dir/manifest.json') as Map<String, dynamic>;
  if (manifest['language'] != languageVersion()) {
    throw StateError(
      'The IR is language ${manifest['language']}, the source is ${languageVersion()}',
    );
  }
  final files = manifest['files'] as Map<String, dynamic>;
  for (final MapEntry(key: name, value: sum) in files.entries) {
    final actual = sha256
        .convert(File('$dir/$name').readAsBytesSync())
        .toString();
    if (actual != sum) {
      throw StateError(
        'The IR file $name does not match its checksum in the manifest',
      );
    }
  }
}

/// The name of a token in lowerCamelCase: color.role.accent-fg gives roleAccentFg in MonoColors. If the first part of
/// the path is the name of the type (color, duration), the name does not include it.
String memberName(String path, String type) {
  final parts = path.split('.');
  final words = [
    for (final p in parts.first == type ? parts.skip(1) : parts)
      ...p.split('-'),
  ];
  return words.first +
      words.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
}

String _pascal(String s) =>
    s.split('-').map((w) => w[0].toUpperCase() + w.substring(1)).join();

/// A color of the IR as a Dart constant.
String _color(Map<String, dynamic> c) {
  final hex = (c['hex'] as String).substring(1).toUpperCase();
  final alpha = (c['alpha'] as num).toDouble();
  if (alpha == 1) return 'Color(0xFF$hex)';
  String channel(int i) =>
      (int.parse(hex.substring(i, i + 2), radix: 16) / 255).toString();
  return 'Color.from(alpha: $alpha, red: ${channel(0)}, green: ${channel(2)}, blue: ${channel(4)})';
}

/// The Dart type and the Dart constant of a plain value of the four types of the stub.
(String, String)? _value(String type, Object? v) {
  switch (type) {
    case 'color':
      return ('Color', _color(v as Map<String, dynamic>));
    case 'dimension':
      final d = v as Map<String, dynamic>;
      if (d['unit'] != 'px') {
        throw StateError('The emitter knows only px, not ${d['unit']}');
      }
      return ('double', '${(d['value'] as num).toDouble()}');
    case 'duration':
      final d = v as Map<String, dynamic>;
      if (d['unit'] != 'ms') {
        throw StateError('The emitter knows only ms, not ${d['unit']}');
      }
      return ('Duration', 'Duration(milliseconds: ${d['value']})');
    case 'number':
      return ('double', '${(v as num).toDouble()}');
  }
  return null;
}

/// The classes of the four types, in the order of the file.
const _classes = {
  'color': ('MonoColors', 'The color tokens.'),
  'dimension': ('MonoDimensions', 'The dimension tokens, in logical pixels.'),
  'duration': ('MonoDurations', 'The duration tokens.'),
  'number': ('MonoNumbers', 'The number tokens: the opacities and the scales.'),
};

/// The text of the generated file.
String emit() {
  final dir = irDir();
  final canonical = _json('$dir/canonical.json') as Map<String, dynamic>;
  final axes = _json('$dir/axes.json') as Map<String, dynamic>;
  final manifest = _json('$dir/manifest.json') as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/emit.dart from language/ir/${manifest['language']}/. Do not edit: change the language source.',
    )
    ..writeln()
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln('/// The language version of these tokens.')
    ..writeln("const String language = '${manifest['language']}';");

  // The axes: an enum of the contexts, and a class with one value for each context.
  for (final MapEntry(key: axis, value: a as Map<String, dynamic>)
      in axes.entries) {
    final contexts = (a['contexts'] as List).cast<String>();
    final name = _pascal(axis);
    out
      ..writeln()
      ..writeln(
        '/// The contexts of the axis $axis. The fallback is ${a['default']}.',
      )
      ..writeln('enum Mono$name { ${contexts.join(', ')} }')
      ..writeln()
      ..writeln('/// A value for each context of the axis $axis.')
      ..writeln('final class By$name<T> {')
      ..writeln(
        '  const By$name({${contexts.map((c) => 'required this.$c').join(', ')}});',
      )
      ..writeln();
    for (final c in contexts) {
      out
        ..writeln('  /// The value of the context $c.')
        ..writeln('  final T $c;')
        ..writeln();
    }
    out
      ..writeln('  /// The value of the context [context].')
      ..writeln(
        '  T of(Mono$name context) => switch (context) { ${contexts.map((c) => 'Mono$name.$c => $c').join(', ')} };',
      )
      ..writeln('}');
  }

  // The tokens: one class for each type.
  for (final MapEntry(key: type, value: (cls, doc)) in _classes.entries) {
    out
      ..writeln()
      ..writeln('/// $doc')
      ..writeln('abstract final class $cls {');
    for (final MapEntry(key: path, value: e as Map<String, dynamic>)
        in canonical.entries) {
      if (e['type'] != type) continue;
      final description = e['description'] as String?;
      out.writeln(
        description == null
            ? '  /// The token $path.'
            : '  /// $path: ${description.trim().replaceAll(RegExp(r'\s+'), ' ')}',
      );
      final tokenAxes = (e['axes'] as List?)?.cast<String>();
      if (tokenAxes == null) {
        final (t, v) = _value(type, e['value'])!;
        out.writeln('  static const $t ${memberName(path, type)} = $v;');
        continue;
      }
      if (tokenAxes.length != 1) {
        throw StateError(
          '$path changes with ${tokenAxes.join(' and ')}: the emitter knows one axis for each token',
        );
      }
      final axis = tokenAxes.single;
      // A key of values is <axis>=<context>, for example theme=dark.
      final pairs = [
        for (final MapEntry(key: k, value: v)
            in (e['values'] as Map<String, dynamic>).entries)
          (k.split('=')[1], _value(type, v)!),
      ];
      final t = pairs.first.$2.$1;
      final args = pairs.map((p) => '${p.$1}: ${p.$2.$2}').join(', ');
      out.writeln(
        '  static const By${_pascal(axis)}<$t> ${memberName(path, type)} = By${_pascal(axis)}($args);',
      );
    }
    out.writeln('}');
  }
  return out.toString();
}

void main(List<String> args) {
  final text = emit();
  final file = File(output);
  if (args.contains('--check')) {
    verifyIr();
    if (!file.existsSync() || file.readAsStringSync() != text) {
      stderr.writeln(
        'emit: $output differs from the output of the emitter. Run: dart run tool/emit.dart',
      );
      exitCode = 1;
      return;
    }
    stdout.writeln(
      'emit: the IR of language ${languageVersion()} matches its manifest, and $output matches the IR.',
    );
    return;
  }
  file
    ..createSync(recursive: true)
    ..writeAsStringSync(text);
  stdout.writeln('emit: wrote $output');
}
